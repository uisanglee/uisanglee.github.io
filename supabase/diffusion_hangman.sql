create table if not exists public.diffusion_hangman_scores (
  id bigint generated by default as identity primary key,
  play_date date not null default ((now() at time zone 'utc')::date),
  device_id uuid not null,
  nickname text not null check (char_length(nickname) between 5 and 40),
  attempts smallint not null check (attempts between 1 and 10),
  completed_at timestamptz not null default now(),
  unique (play_date, device_id)
);

alter table public.diffusion_hangman_scores
  drop constraint if exists diffusion_hangman_scores_attempts_check;
alter table public.diffusion_hangman_scores
  add constraint diffusion_hangman_scores_attempts_check
  check (attempts between 1 and 10) not valid;

alter table public.diffusion_hangman_scores enable row level security;
revoke all on table public.diffusion_hangman_scores from anon, authenticated;

create or replace function public.get_diffusion_hangman_leaderboard()
returns table (rank bigint, nickname text, attempts smallint, completed_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select
    row_number() over (order by s.attempts asc, s.completed_at asc) as rank,
    s.nickname,
    s.attempts,
    s.completed_at
  from public.diffusion_hangman_scores s
  where s.play_date = ((now() at time zone 'utc')::date)
    and s.attempts between 1 and 10
  order by s.attempts asc, s.completed_at asc
  limit 20;
$$;

create or replace function public.submit_diffusion_hangman_score(
  p_device_id uuid,
  p_nickname text,
  p_attempts integer
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if p_attempts < 1 or p_attempts > 10 then
    raise exception 'Attempts must be between 1 and 10';
  end if;

  if char_length(p_nickname) < 5 or char_length(p_nickname) > 40
     or p_nickname !~ '^[A-Za-z0-9 -]+$' then
    raise exception 'Invalid nickname';
  end if;

  insert into public.diffusion_hangman_scores (play_date, device_id, nickname, attempts)
  values (((now() at time zone 'utc')::date), p_device_id, p_nickname, p_attempts)
  on conflict (play_date, device_id) do nothing;

  return found;
end;
$$;

revoke all on function public.get_diffusion_hangman_leaderboard() from public;
revoke all on function public.submit_diffusion_hangman_score(uuid, text, integer) from public;
grant execute on function public.get_diffusion_hangman_leaderboard() to anon, authenticated;
grant execute on function public.submit_diffusion_hangman_score(uuid, text, integer) to anon, authenticated;
